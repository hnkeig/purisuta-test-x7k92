/* {名前} などの差しこみ口を実際の言葉に置きかえる。配列もそのまま渡せます */
function fmt(s,v){
  if(Array.isArray(s))return s.map(x=>fmt(x,v));
  if(typeof s!=="string")return s;
  if(v)for(const k in v)s=s.split("{"+k+"}").join(v[k]);
  return s;
}

