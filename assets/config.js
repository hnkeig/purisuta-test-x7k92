/* ---- 無料ホームページの「広告よけ」------------------------------------
   忍者ホームページ（gozaru.jp など）の無料スペースに置くと、サーバーが
   ページの終わりに広告を勝手に足します。その広告は
     ・画面のまんなか寄せ
     ・z-index が 9999（ゲームのどの部品よりも上）
   なので、そのままだとゲーム画面の上のまんなかにかぶさって、
     ・選択肢の**まんなかだけ押せない**（両はしは押せる）
     ・スマホでは**ボタンがほとんど押せない**（音だけ鳴る）
   ということが起きます。

   avoid を true にしておくと、広告の高さを測って、そのぶんだけ
   ゲーム画面を下げます（広告は消しません。消すと規約ちがいになります）。
   よける相手がいないとき（自分のサーバー・file://・1ファイル版）は
   なにも起きないので、そのままで大丈夫です。

   ※ 広告のない置き場所（GitHub Pages、Netlify、Cloudflare Pages など）に
     移すと、ゲームを画面いっぱいのまま遊べます。 */
